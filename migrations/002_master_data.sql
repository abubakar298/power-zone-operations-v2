CREATE TABLE customers (
 id integer PRIMARY KEY CHECK(id>=0), name text NOT NULL CHECK(length(name)>0),
 short_code text NOT NULL CHECK(length(short_code)>0), contact_person text NOT NULL DEFAULT '',
 phone text NOT NULL DEFAULT '', email text NOT NULL DEFAULT '', address text NOT NULL DEFAULT '',
 status text NOT NULL CHECK(status IN ('Active','Inactive')), notes text NOT NULL DEFAULT '',
 version integer NOT NULL DEFAULT 1 CHECK(version>0)
);
CREATE UNIQUE INDEX customers_short_code_unique ON customers(lower(short_code));
CREATE TABLE sites (
 id integer PRIMARY KEY CHECK(id>0), customer_id integer NOT NULL REFERENCES customers(id),
 name text NOT NULL, code text NOT NULL, location text NOT NULL DEFAULT '',
 status text NOT NULL CHECK(status IN ('Active','Inactive')), version integer NOT NULL DEFAULT 1
);
CREATE TABLE brands (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, category text NOT NULL,name text NOT NULL,
 status text NOT NULL CHECK(status IN ('Active','Inactive')),notes text NOT NULL DEFAULT '',
 version integer NOT NULL DEFAULT 1, UNIQUE(category,name)
);
CREATE TABLE item_master (
 key text PRIMARY KEY, unit text NOT NULL, approved_specification text,
 version integer NOT NULL DEFAULT 1
);
CREATE TABLE rate_versions (
 key text NOT NULL REFERENCES item_master(key),version integer NOT NULL CHECK(version>0),
 rate numeric(18,4) CHECK(rate>=0),status text NOT NULL CHECK(status IN ('Active','Needs Rate','Inactive')),
 notes text NOT NULL DEFAULT '',created_at timestamptz NOT NULL DEFAULT now(),created_by uuid REFERENCES users(id),
 PRIMARY KEY(key,version)
);
CREATE TABLE rule_versions (
 key text NOT NULL,version integer NOT NULL CHECK(version>0),rule_group text NOT NULL,setting text NOT NULL,
 value numeric(18,4) NOT NULL CHECK(value>=0),notes text NOT NULL DEFAULT '',
 created_at timestamptz NOT NULL DEFAULT now(),created_by uuid REFERENCES users(id),PRIMARY KEY(key,version)
);
CREATE TABLE inverter_configurations (
 configuration text PRIMARY KEY,total_kw numeric(8,2) NOT NULL CHECK(total_kw>0),
 sku text NOT NULL REFERENCES item_master(key),quantity integer NOT NULL CHECK(quantity>0)
);
CREATE TABLE costing_classifications (phase text NOT NULL,epc_category text NOT NULL,item_rule text PRIMARY KEY,notes text NOT NULL);
CREATE TABLE master_imports (source_sha256 text PRIMARY KEY, imported_at timestamptz NOT NULL DEFAULT now(),counts jsonb NOT NULL);
CREATE FUNCTION prevent_master_version_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'Master versions are immutable; append a new version'; END; $$;
CREATE TRIGGER immutable_rates BEFORE UPDATE OR DELETE ON rate_versions FOR EACH ROW EXECUTE FUNCTION prevent_master_version_mutation();
CREATE TRIGGER immutable_rules BEFORE UPDATE OR DELETE ON rule_versions FOR EACH ROW EXECUTE FUNCTION prevent_master_version_mutation();
