import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';

test('setup, invalid login, dashboard, reload, process restart, logout, relogin, mobile', async ({page,context}) => {
  const errors: string[]=[];
  page.on('pageerror',err => errors.push(err.message));
  await page.goto('/');
  await expect(page.getByRole('heading',{name:'Your workspace starts here.'})).toBeVisible();
  await page.getByLabel('Full name').fill('Abu Bakar Siddique');
  await page.getByLabel('Email address').fill('admin@example.test');
  await page.getByLabel('Password',{exact:true}).fill('browser-test-passphrase-298');
  await page.getByLabel('Confirm password').fill('browser-test-passphrase-298');
  await page.getByLabel('Setup key').fill('browser-test-setup-key-isolated-only');
  await page.getByRole('button',{name:'Create administrator'}).click();
  await expect(page.getByRole('heading',{name:'Welcome back.'})).toBeVisible();
  await page.getByLabel('Email address').fill('admin@example.test');
  await page.getByLabel('Password',{exact:true}).fill('incorrect');
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await expect(page.getByRole('alert')).toHaveText('Email or password is incorrect.');
  await page.getByLabel('Password',{exact:true}).fill('browser-test-passphrase-298');
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Welcome, Abu Bakar Siddique.'})).toBeVisible();
  await expect(page.getByRole('heading',{name:'You’re ready to get started.'})).toBeVisible();
  await page.getByRole('button',{name:'My account',exact:true}).click();
  await expect(page.getByRole('heading',{name:'My account',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Dashboard',exact:true}).click();
  await page.reload();
  await expect(page.getByRole('heading',{name:'Welcome, Abu Bakar Siddique.'})).toBeVisible();
  await page.getByRole('button',{name:'Master data',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Master data',exact:true})).toBeVisible();
  await expect(page.getByRole('tab',{name:'Customers 286'})).toBeVisible();
  await page.getByLabel('Search customers').fill('Meezan');
  await expect(page.getByRole('cell',{name:'MBL',exact:true})).toBeVisible();
  await page.getByRole('tab',{name:'Sites 4'}).click();
  await expect(page.getByRole('cell',{name:'0128',exact:true})).toBeVisible();
  await page.getByRole('tab',{name:'Items & specifications 57'}).click();
  await page.getByLabel('Specification status').selectOption('Need to enter');
  await expect(page.getByRole('cell',{name:'Solar PV Modules',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Edit Solar PV Modules',exact:true}).click();
  await page.getByLabel('Technical specification').fill('Approved browser-test specification');
  await page.getByLabel('Status',{exact:true}).selectOption('Approved');
  await page.getByRole('button',{name:'Save changes',exact:true}).click();
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await expect(page.getByRole('cell',{name:'Solar PV Modules',exact:true})).not.toBeVisible();
  await page.getByLabel('Specification status').selectOption('Approved');
  await expect(page.getByRole('cell',{name:'Approved browser-test specification',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'History Solar PV Modules',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Version history'})).toBeVisible();
  await page.getByRole('button',{name:'Close history'}).click();
  await page.getByRole('button',{name:'Dashboard',exact:true}).click();
  const cookieBefore = (await context.cookies()).find(c=>c.name==='pz_session')?.value;
  const control=JSON.parse(await readFile('.local/e2e-control.json','utf8')) as {pid:number};
  process.kill(control.pid,'SIGUSR2');
  // Give the supervisor time to stop the old process, then wait for readiness.
  await new Promise(resolve=>setTimeout(resolve,600));
  await expect.poll(async()=>{try{return (await fetch('http://127.0.0.1:3180/api/health')).status;}catch{return 0;}},{timeout:15000}).toBe(200);
  await page.reload();
  await expect(page.getByRole('heading',{name:'Welcome, Abu Bakar Siddique.'})).toBeVisible();
  await expect(page.getByRole('heading',{name:'You’re ready to get started.'})).toBeVisible();
  expect((await context.cookies()).find(c=>c.name==='pz_session')?.value).toBe(cookieBefore);
  await page.screenshot({path:'test-results/dashboard-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'Sign out'}).click();
  await expect(page.getByRole('heading',{name:'Welcome back.'})).toBeVisible();
  await page.goto('/dashboard');
  await expect(page.getByRole('heading',{name:'Welcome back.'})).toBeVisible();
  const replay = await context.request.get('/api/dashboard',{headers:{Cookie:`pz_session=${cookieBefore}`}});
  expect(replay.status()).toBe(401);
  await page.setViewportSize({width:390,height:844});
  await page.getByLabel('Email address').fill('admin@example.test');
  await page.getByLabel('Password',{exact:true}).fill('browser-test-passphrase-298');
  await page.screenshot({path:'test-results/login-mobile.png',fullPage:true});
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Welcome, Abu Bakar Siddique.'})).toBeVisible();
  await expect(page.getByRole('heading',{name:'You’re ready to get started.'})).toBeVisible();
  await page.screenshot({path:'test-results/dashboard-mobile.png',fullPage:true});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await page.getByRole('button',{name:'Toggle navigation'}).click();
  await page.getByRole('button',{name:'My account',exact:true}).click();
  await expect(page.getByRole('heading',{name:'My account',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Abu Bakar Siddique Admin'}).click();
  await expect(page.locator('#account-menu')).toBeVisible();
  await page.getByRole('button',{name:'Abu Bakar Siddique Admin'}).click();
  expect(errors).toEqual([]);
  await page.getByRole('button',{name:'Sign out'}).click();
  await expect(page.getByRole('heading',{name:'Welcome back.'})).toBeVisible();
});
