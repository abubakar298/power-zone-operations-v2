import { test } from "node:test";
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { resolve } from "node:path";
import { chromium } from "@playwright/test";
import { testDatabase } from "./database.js";
import { createApp } from "../server/app.js";
import { readConfig } from "../server/config.js";
import { digest, newToken } from "../server/auth/crypto.js";
test("C&I employee browser: select family, customer, standard price, PDF and resume",async()=>{
 const db=await testDatabase();let browser:any,server:any;
 try{
  const id=randomUUID(),token=newToken(),csrf=newToken();
  await db.pool.query("UPDATE admin_bootstrap SET completed_at=now()");
  await db.pool.query("INSERT INTO users(id,email,display_name,password_hash,role) VALUES($1,'cni-browser@example.test','CNI Browser','isolated','Coordinator')",[id]);
  await db.pool.query("INSERT INTO auth_sessions(token_hash,user_id,csrf_token,expires_at) VALUES($1,$2,$3,now()+interval '1 hour')",[digest(token),id,csrf]);
  const cfg=readConfig({NODE_ENV:"test",APP_ORIGIN:"http://127.0.0.1:3000",DATABASE_URL:db.url,ADMIN_SETUP_TOKEN:"cni-browser-setup-token-12345678"});
  const app=createApp(db.pool,cfg,resolve("dist/web"));server=app.listen(0,"127.0.0.1");await new Promise<void>(r=>server.once("listening",r));
  const origin=`http://127.0.0.1:${server.address().port}`;cfg.origin=origin;
  browser=await chromium.launch({headless:true});const context=await browser.newContext();await context.addCookies([{name:"pz_session",value:token,url:origin}]);
  const page=await context.newPage();page.on("dialog",(d:{accept:()=>Promise<void>})=>d.accept());await page.goto(origin+"/dashboard");
  await page.getByRole("button",{name:"Survey & BOQ",exact:true}).click();await page.getByRole("button",{name:"New BOQ",exact:true}).click();
  await page.getByLabel("BOQ type",{exact:true}).selectOption("ci-bess");
  await page.getByPlaceholder("Search customer name or phone").fill("Bank Alfalah");await page.getByLabel("Select matching customer").selectOption("3");
  await page.getByLabel("Site / Project name").fill("Isolated browser sample");
  await page.getByLabel("Cabinet quantity").fill("2");
  assert.match(await page.locator(".summary-grid").innerText(),/34,500,000/);
  await page.getByLabel("Tax presentation").selectOption("Separate");
  assert.match(await page.locator(".summary-grid").innerText(),/GST 18%/);
  await page.getByRole("button",{name:"Save & send for approval",exact:true}).click();
  await page.getByRole("status").filter({hasText:"Saved and sent for quotation approval"}).waitFor();
  assert.equal(await db.pool.query("SELECT count(*) AS n FROM cni_proposal_versions").then(r=>Number(r.rows[0].n)),1);
  assert.equal(await page.getByRole("link",{name:"Open proposal PDF (draft)",exact:true}).count(),1);
  await page.getByRole("button",{name:"Create revision",exact:true}).click();await page.getByLabel("Cabinet quantity").waitFor();
  assert.equal(await page.getByLabel("Cabinet quantity").inputValue(),"2");
  assert.equal(await page.getByText("Management financial review",{exact:true}).count(),0);
  const managerId=randomUUID(),managerToken=newToken(),managerCsrf=newToken();
  await db.pool.query("INSERT INTO users(id,email,display_name,password_hash,role) VALUES($1,'cni-manager@example.test','CNI Manager','isolated','Management')",[managerId]);
  await db.pool.query("INSERT INTO auth_sessions(token_hash,user_id,csrf_token,expires_at) VALUES($1,$2,$3,now()+interval '1 hour')",[digest(managerToken),managerId,managerCsrf]);
  const managementContext=await browser.newContext();await managementContext.addCookies([{name:"pz_session",value:managerToken,url:origin}]);
  const manager=await managementContext.newPage();manager.on("dialog",(d:{accept:()=>Promise<void>})=>d.accept());await manager.goto(origin+"/dashboard");
  await manager.getByRole("button",{name:"Survey & BOQ",exact:true}).click();await manager.getByRole("button",{name:"New BOQ",exact:true}).click();await manager.getByLabel("BOQ type",{exact:true}).selectOption("ci-bess");
  await manager.getByRole("button",{name:"Open",exact:true}).click();await manager.getByRole("heading",{name:"Management financial review",exact:true}).waitFor();
  await manager.getByLabel("Target markup (%)",{exact:true}).fill("30");
  await manager.getByText("33,748,000.00",{exact:true}).waitFor();
  assert.match(await manager.locator(".detail-panel").last().innerText(),/22,000,000/);
  await manager.getByRole("button",{name:"Approve quotation",exact:true}).click();await manager.getByRole("cell",{name:"Approved",exact:true}).waitFor();
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.getByRole("button",{name:"Save & send for approval",exact:true}).isVisible(),true);
 }finally{if(browser)await browser.close();if(server)await new Promise<void>(r=>server.close(()=>r()));await db.close();}
});
