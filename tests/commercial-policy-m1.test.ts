import test from "node:test";
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import request from "supertest";
import { Decimal } from "decimal.js";
import { testDatabase } from "./database.js";
import { CommercialRepository } from "../server/commercial/repository.js";
import { MastersRepository } from "../server/masters/repository.js";
import { calculate } from "../server/boq/engine.js";
import { surveySchema } from "../server/boq/schema.js";
import { price, quote } from "../server/commercial/engine.js";
import { pricingSchema, quotationSchema } from "../server/commercial/schema.js";
import { createApp } from "../server/app.js";
import { readConfig } from "../server/config.js";
import { fingerprint } from "../server/boq/repository.js";

test("M1 isolated migration, policy authorization, automatic item prices and immutable history", async () => {
  const db = await testDatabase();
  try {
    const repo = new CommercialRepository(db.pool),
      origin = "http://localhost:3000";
    const app = createApp(
      db.pool,
      readConfig({
        NODE_ENV: "test",
        APP_ORIGIN: origin,
        DATABASE_URL: db.url,
        ADMIN_SETUP_TOKEN: "m1-isolated-test-setup-token-12345678",
      }),
    );
    await request(app)
      .post("/api/auth/setup")
      .set("Origin", origin)
      .send({
        email: "m1@example.test",
        displayName: "M1 Admin",
        password: "m1-isolated-password-12345",
        setupToken: "m1-isolated-test-setup-token-12345678",
      })
      .expect(201);
    const login = await request(app)
      .post("/api/auth/login")
      .set("Origin", origin)
      .send({
        email: "m1@example.test",
        password: "m1-isolated-password-12345",
      })
      .expect(200);
    const admin = login.body.user.id,
      cookie = login.headers["set-cookie"][0].split(";")[0],
      csrf = login.body.csrfToken;
    // This suite compares full immutable financial payloads. Normal Admin API
    // responses intentionally redact confidential costs without this grant.
    await db.pool.query("INSERT INTO restricted_cost_access(user_id,granted_reason) VALUES($1,'Isolated immutable financial snapshot regression')",[admin]);
    const post = (path: string, body: object) =>
      request(app)
        .post(path)
        .set("Origin", origin)
        .set("Cookie", cookie)
        .set("X-CSRF-Token", csrf)
        .send(body);
    const policy = await repo.standardPolicy(admin);
    assert.equal(policy.version, 3);
    assert.equal(policy.costUpliftPercent, "5");
    assert.equal(policy.preapprovedCostDiscountPercent, "5");
    assert.deepEqual(policy.markups, {
      solar: "10",
      structure: "10",
      earthing: "10",
      bess: "30",
      other: "25",
    });
    await request(app)
      .post("/api/commercial/standard-policy")
      .set("Cookie", cookie)
      .set("Origin", origin)
      .send({
        expectedVersion: policy.version,
        policy: {
          markups: policy.markups,
          itemCategories: policy.itemCategories,
        },
      })
      .expect(403);
    await request(app).get("/api/commercial/standard-policy").expect(401);
    for (const role of [
      "Coordinator",
      "Operations",
      "Inventory",
      "Accounts",
      "Design",
    ]) {
      const id = randomUUID(),
        token = (id + id).replaceAll("-", "").slice(0, 43);
      await db.pool.query(
        "INSERT INTO users(id,email,display_name,password_hash,role) VALUES($1,$2,$3,'unused',$4)",
        [id, id + "@example.test", role, role],
      );
      await assert.rejects(
        repo.saveStandardPolicy(
          id,
          { markups: policy.markups, itemCategories: policy.itemCategories },
          1,
        ),
        /Management approval|Commercial preparation/,
      );
      // Session hashes are generated by the production helper; no credentials leave this disposable database.
      const { createHash } = await import("node:crypto");
      await db.pool.query(
        "INSERT INTO auth_sessions(token_hash,user_id,csrf_token,expires_at) VALUES($1,$2,$3,now()+interval '1 hour')",
        [createHash("sha256").update(token).digest("hex"), id, "m1-csrf-token"],
      );
      await request(app)
        .post("/api/commercial/standard-policy")
        .set("Cookie", "pz_session=" + token)
        .set("Origin", origin)
        .set("X-CSRF-Token", "m1-csrf-token")
        .send({
          expectedVersion: policy.version,
          policy: {
            markups: policy.markups,
            itemCategories: policy.itemCategories,
          },
        })
        .expect(403);
      await request(app)
        .get("/api/commercial/standard-policy")
        .set("Cookie", "pz_session=" + token)
        .expect(403);
    }
    const m = await new MastersRepository(db.pool).list(),
      brand = (c: string) =>
        m.brands.find((b) => b.category === c && b.status === "Active")!.id;
    const survey = surveySchema.parse({
      customerId: 3,
      siteName: "Isolated M1",
      siteCode: "M1",
      location: "Isolated",
      panelQty: 20,
      panelWattage: "550",
      structure: "Elevated",
      dcMetres: "100",
      earth25: "20",
      earth6: "30",
      earth10: "30",
      inverter: "12 kW",
      batteryKwh: 20,
      smartMeter: false,
      genset: false,
      brands: {
        solar: brand("Solar Panel"),
        inverter: brand("Inverter"),
        battery: brand("Battery & BMS"),
        cable: brand("Cable"),
        switchgear: brand("Switchgear"),
      },
      preparedBy: "M1 Admin",
    });
    const boq = calculate(survey, m),
      input = pricingSchema.parse({
        boqRevisionId: randomUUID(),
        presentation: "Full Breakup",
        taxMode: "Show Sales Tax Separately",
        preparedBy: "M1 Admin",
        markups: {
          solar: "99",
          structure: "99",
          bess: "99",
          earthing: "99",
          balance: "99",
          rest: "99",
        },
      });
    const snapshot = price(boq, "M1-R0", input, policy);
    for (const l of snapshot.itemPricing!)
      assert.equal(
        l.beforeTax,
        new Decimal(l.cost)
          .mul(new Decimal(l.markup).add(policy.costUpliftPercent ?? "0").div(100).add(1))
          .toString(),
      );
    assert.equal(
      snapshot.itemPricing!.find((l) => l.key === "6mm² Earthing Cable")!
        .markup,
      "25",
    );
    assert.equal(
      snapshot.itemPricing!.find((l) => l.key === "6mm² DC Cable Red")!.markup,
      "25",
    );
    assert.equal(
      snapshot.itemPricing!.find((l) => l.key === "HYB-3P-012")!.markup,
      "30",
    );
    assert.equal(
      snapshot.itemPricing!.find((l) => l.key === "Earthing Bore")!.markup,
      "10",
    );
    assert.equal(snapshot.input.markups.solar, "10");
    assert.equal(
      new Decimal(snapshot.subtotal).add(snapshot.tax).toFixed(2),
      snapshot.total,
    );
    const original = JSON.stringify(snapshot);
    for (const presentation of [
      "No Breakup",
      "Basic Breakup",
      "Full Breakup",
    ] as const)
      for (const taxMode of [
        "Tax Included",
        "Show Sales Tax Separately",
      ] as const) {
        const p = price(
          boq,
          "M1-R0",
          { ...input, presentation, taxMode },
          policy,
        );
        assert.equal(p.total, snapshot.total);
        const q = quote(
          p,
          boq,
          quotationSchema.parse({
            pricingId: randomUUID(),
            quotedDate: "2026-10-08",
            validity: "15 days",
            proposedBy: "M1",
            discount: "0",
          }),
        );
        if (presentation !== "No Breakup")
          assert.equal(
            q.lines
              .reduce((s, l) => s.add(l.amount ?? 0), new Decimal(0))
              .toFixed(2),
            taxMode === "Tax Included" ? p.total : p.subtotal,
          );
      }
    const unknown = {
      ...boq,
      lines: boq.lines.map((l, i) =>
        i === 0 ? { ...l, key: "Unclassified new product" } : l,
      ),
    };
    assert.throws(
      () => price(unknown, "M1-R0", input, policy),
      /classification required/,
    );
    const extra = {
      ...boq,
      survey: {
        ...boq.survey,
        additionalItem: {
          description: "Additional cable",
          specification: "",
          qty: "1",
          unit: "m",
          unitCost: "100.01",
          taxRate: "18" as const,
        },
      },
      lines: [
        ...boq.lines,
        {
          ...boq.lines[0],
          key: "Additional Item",
          description: "Additional cable",
          phase: "EPC",
          epc: "Installation Cost",
          total: "100.01",
        },
      ],
      total: new Decimal(boq.total).add("100.01").toString(),
    };
    assert.throws(
      () => price(extra, "M1-extra", input, policy),
      /classification required/,
    );
    const classified = price(
      extra,
      "M1-extra",
      { ...input, additionalCategory: "other" },
      policy,
    );
    assert.equal(classified.itemPricing!.at(-1)!.beforeTax, "130.013");
    assert.equal(classified.itemPricing!.at(-1)!.markup, "25");
    const next = await repo.saveStandardPolicy(
      admin,
      {
        markups: { ...policy.markups, solar: "11" },
        itemCategories: policy.itemCategories,
      },
      policy.version,
    );
    assert.equal(next.version, policy.version + 1);
    assert.equal(JSON.stringify(snapshot), original);
    assert.equal(snapshot.policy!.markups.solar, "10");
    await assert.rejects(
      db.pool.query(
        "UPDATE standard_commercial_policy_versions SET policy=policy WHERE version=1",
      ),
      /immutable/,
    );
    await assert.rejects(
      repo.saveStandardPolicy(
        admin,
        { markups: policy.markups, itemCategories: policy.itemCategories },
        1,
      ),
      /Policy changed/,
    );
    // Exercise approved BOQ -> preview/save with automatic policy and immutable commercial snapshot.
    const d = (
      await post("/api/boqs/drafts", { version: 0, inputs: survey }).expect(200)
    ).body;
    const p = (await post("/api/boqs/preview", survey).expect(200)).body;
    const review = (
      await post("/api/boqs/reviews", {
        draftId: d.id,
        version: d.version,
        fingerprint: p.fingerprint,
      }).expect(201)
    ).body;
    const approved = (
      await post(`/api/boqs/reviews/${review.id}/decision`, {
        outcome: "Approved",
        comments: "M1 isolated",
      }).expect(200)
    ).body.saved;
    const body = { ...input, boqRevisionId: approved.id };
    const preview = (
      await post("/api/commercial/pricing/preview", body).expect(200)
    ).body;
    assert.equal(preview.snapshot.policy.version, policy.version + 1);
    const saved = (
      await post("/api/commercial/pricing", {
        ...body,
        fingerprint: preview.fingerprint,
        requestKey: randomUUID(),
      }).expect(201)
    ).body;
    assert.equal(saved.snapshot.policy.version, policy.version + 1);
    assert.equal(saved.fingerprint, fingerprint(saved.snapshot));
    // Management preview works identically for tax-inclusive and separate-tax presentations.
    const qi = quotationSchema.parse({
      pricingId: saved.id,
      quotedDate: "2026-10-08",
      validity: "7 days",
      proposedBy: "M1",
      discount: "0",
    });
    const qp = await repo.quotationPreview(admin, qi);
    const issued = await repo.quotationSave(
      admin,
      qi,
      qp.fingerprint,
      randomUUID(),
    );
    const reviewUrl = `/api/commercial/quotations/${issued.id}/discount-review`;
    await request(app)
      .post(reviewUrl)
      .set("Origin", origin)
      .set("Cookie", cookie)
      .send({ targetMargin: "10" })
      .expect(403);
    await post(reviewUrl, { targetMargin: "10", discount: "1" }).expect(400);
    await post(reviewUrl, { targetMargin: "100" }).expect(400);
    const reviewMargin = (
      await post(reviewUrl, { targetMargin: "10" }).expect(200)
    ).body;
    assert.equal(reviewMargin.proposed.marginPercent, "10.00");
    assert.ok(new Decimal(reviewMargin.discount).gt(0));
    assert.equal(
      new Decimal(reviewMargin.proposed.revenue)
        .minus(saved.snapshot.cost)
        .toFixed(2),
      reviewMargin.proposed.profit,
    );
    const lump = (
      await post(reviewUrl, { discount: reviewMargin.discount }).expect(200)
    ).body;
    assert.deepEqual(lump.proposed, reviewMargin.proposed);
    const includedSurvey = {
      ...survey,
      siteName: "Isolated Included",
      siteCode: "M1-INCL",
    };
    const di = (
      await post("/api/boqs/drafts", {
        version: 0,
        inputs: includedSurvey,
      }).expect(200)
    ).body;
    const pi = (await post("/api/boqs/preview", includedSurvey).expect(200))
      .body;
    const ri = (
      await post("/api/boqs/reviews", {
        draftId: di.id,
        version: di.version,
        fingerprint: pi.fingerprint,
      }).expect(201)
    ).body;
    const ai = (
      await post(`/api/boqs/reviews/${ri.id}/decision`, {
        outcome: "Approved",
        comments: "Isolated included",
      }).expect(200)
    ).body.saved;
    const includedInput = {
      ...body,
      boqRevisionId: ai.id,
      taxMode: "Tax Included" as const,
    };
    const includedPreview = await repo.pricingPreview(admin, includedInput);
    const includedPricing = await repo.pricingSave(
      admin,
      includedInput,
      includedPreview.fingerprint,
      randomUUID(),
    );
    const includedQuoteInput = { ...qi, pricingId: includedPricing.id };
    const includedQuotePreview = await repo.quotationPreview(
      admin,
      includedQuoteInput,
    );
    const includedQuote = await repo.quotationSave(
      admin,
      includedQuoteInput,
      includedQuotePreview.fingerprint,
      randomUUID(),
    );
    const includedReview = await repo.discountReview(admin, includedQuote.id, {
      targetMargin: "10",
    });
    assert.deepEqual(includedReview.proposed, reviewMargin.proposed);
    assert.equal(includedReview.discount, reviewMargin.discount);
    const reset = (await post(reviewUrl, { discount: "0" }).expect(200)).body;
    assert.deepEqual(reset.original, reset.proposed);
    for (const role of [
      "Coordinator",
      "Operations",
      "Inventory",
      "Accounts",
      "Design",
    ]) {
      const user = (
        await db.pool.query("SELECT id FROM users WHERE role=$1 LIMIT 1", [
          role,
        ])
      ).rows[0];
      await assert.rejects(
        repo.discountReview(user.id, issued.id, { targetMargin: "10" }),
        /not|permission|Management|management|access|Forbidden/i,
      );
    }
    assert.deepEqual(
      (await repo.quotationGet(issued.id)).snapshot,
      issued.snapshot,
    );
    const managerId = randomUUID();
    await db.pool.query(
      "INSERT INTO users(id,email,display_name,password_hash,role) VALUES($1,$2,'Manager','unused','Management')",
      [managerId, managerId + "@example.test"],
    );
    const managementPolicy = await repo.saveStandardPolicy(
      managerId,
      { markups: policy.markups, itemCategories: policy.itemCategories },
      policy.version + 1,
    );
    assert.equal(managementPolicy.version, policy.version + 2);
    assert.deepEqual(
      (await repo.pricingGet(admin, saved.id)).snapshot,
      saved.snapshot,
    );
    const stale = await repo.pricingPreview(admin, body);
    await repo.saveStandardPolicy(
      managerId,
      {
        markups: { ...policy.markups, solar: "12" },
        itemCategories: policy.itemCategories,
      },
      policy.version + 2,
    );
    await assert.rejects(
      repo.pricingSave(admin, body, stale.fingerprint, randomUUID()),
      /Preview the current pricing/,
    );
    await assert.rejects(
      db.pool.query(
        "UPDATE commercial_pricing_versions SET snapshot=snapshot WHERE id=$1",
        [saved.id],
      ),
      /immutable/,
    );
  } finally {
    await db.close();
  }
});
